function theme(
  id: string,
  name: string,
  aesthetic: DesignTheme["aesthetic"],
  palette: DesignTheme["palette"],
  fonts: DesignTheme["fonts"],
  opts: Partial<DesignTheme> = {}
): DesignTheme {
  return {
    id,
    name,
    aesthetic,
    mode: opts.mode ?? "light",
    palette,
    fonts,
    spacing: opts.spacing ?? 16,
    density: opts.density ?? "balanced",
    animation: opts.animation ?? "none",
    effects: opts.effects ?? baseEffects,
    atsScore: opts.atsScore ?? 85,
    recruiterScore: opts.recruiterScore ?? 88,
    modernity: opts.modernity ?? 80,
    creativity: opts.creativity ?? 50,
    minimalism: opts.minimalism ?? 70,
  };
}

