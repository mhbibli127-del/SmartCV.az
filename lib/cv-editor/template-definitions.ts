export function defToEditorTemplate(def: DistinctTemplateDef): CvEditorTemplate {
  const catalog = getCatalogEntry(def.slug);
  const source: TemplateMetadata = {
    id: def.id,
    slug: def.slug,
    title: def.name,
    industry: def.industry,
    layout: def.layout,
    theme: def.designTheme,
    tags: [def.designLanguage, def.category.toLowerCase()],
    premium: def.premium,
    animated: false,
    portfolio: def.category === "Creative",
    previewGradient: `linear-gradient(145deg, ${def.colors.primary}, ${def.colors.accent})`,
    category: def.category,
  } as TemplateMetadata & { category: CoreTemplateCategory };

  return {
    id: def.id,
    name: def.name,
    category: def.category,
    thumbnail: def.slug,
    previewImage: catalog?.previewImage ?? getTemplatePreviewPath(def.slug),
    description: catalog?.description ?? def.designLanguage,
    premium: def.premium,
    atsOptimized: def.atsOptimized,
    colors: def.colors,
    fonts: def.fonts,
    layout: def.layout,
    slug: def.slug,
    source,
  };
}

export function getDistinctTemplate(slug: string): DistinctTemplateDef | undefined {
  return DISTINCT_TEMPLATES.find((t) => t.slug === slug || t.id === slug);
}
